// Generation for solvelang-onboard: starter .solve workflows and the
// inference report. Templates use only constructs that appear in the
// repository's own examples (agent blocks, ask, print, comments), and every
// generated block names the signal it came from. Nothing is generated from
// a signal that does not exist.

import type { RepoSignals } from "./signals";

export interface GeneratedFile {
  /** Path relative to the output directory. */
  path: string;
  content: string;
  /** Human-readable signal sources behind this file, for the report. */
  signals: string[];
}

export interface PackSummary {
  packId: string;
  entries: number;
  selectedBytes: number;
  budgetBytes: number;
  truncated: boolean;
}

function solveString(value: string): string {
  // Embed a value in a .solve double-quoted string literal.
  return value.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\r?\n/g, " ");
}

function commandOf(signals: RepoSignals, kind: string) {
  return signals.commands.find((fact) => fact.kind === kind);
}

/**
 * The task text handed to the existing Solve Context pack builder. It is
 * assembled only from evidenced signals (ecosystems, hot paths, and the
 * discovered verification command), because the pack builder ranks sources
 * by matching task words against the workspace.
 */
export function buildPackTask(signals: RepoSignals): string {
  const parts: string[] = ["Orient a new contributor to this repository: its layout, main entry points, and key files."];
  if (signals.ecosystems.length > 0) {
    parts.push(`The repository uses ${signals.ecosystems.map((eco) => eco.name).join(", ")}.`);
  }
  if (signals.hotPaths.length > 0) {
    parts.push(
      `The most frequently changed areas are ${signals.hotPaths.map((hot) => hot.path).join(", ")}.`,
    );
  }
  const test = commandOf(signals, "test");
  if (test) {
    parts.push(`Changes are verified with ${test.command}.`);
  }
  if (signals.testFileCount > 0) {
    parts.push("Include the test files that show how the code is exercised.");
  }
  return parts.join(" ");
}

const HEADER = "// Generated by solvelang-onboard. The signals behind this file are\n// listed in ../onboard-report.md. Edit freely — regeneration overwrites.\n";

export function generateWorkflows(signals: RepoSignals): GeneratedFile[] {
  const files: GeneratedFile[] = [];
  const test = commandOf(signals, "test");
  const build = commandOf(signals, "build");

  files.push({
    path: "workflows/context-pack.solve",
    signals: [
      "Always generated: the starter pack workflow every onboarded repo gets.",
      `Pack task assembled from: ${signals.ecosystems.length} ecosystem signal(s), ${signals.hotPaths.length} hot-path signal(s)${test ? `, test command from ${test.source}` : ""}.`,
    ],
    content:
      HEADER +
      `\nagent ContextGuide {\n` +
      `    instruction "Before changing code, build a Solve Context pack for the task and work from it."\n` +
      `    tool docs\n}\n\n` +
      `ask ContextGuide("${solveString(buildPackTask(signals))}")\n` +
      `print("Starter context pack generated at onboarding: ../context-pack.json")\n`,
  });

  if (test) {
    files.push({
      path: "workflows/validate.solve",
      signals: [`Test command "${test.command}" from ${test.source}.`],
      content:
        HEADER +
        `\nagent Verifier {\n` +
        `    instruction "Verify changes by running the repository test command exactly as stated: ${solveString(test.command)}. Report failures exactly as printed."\n` +
        `    tool docs\n}\n\n` +
        `ask Verifier("Verify the current change set.")\n` +
        `print("Test command (from ${solveString(test.source)}): ${solveString(test.command)}")\n`,
    });
  } else {
    files.push({
      path: "workflows/validate.solve",
      signals: ["No test command was discovered in any guidance file or manifest — the workflow says so instead of inventing one."],
      content:
        HEADER +
        `\nagent Verifier {\n` +
        `    instruction "No test command was discovered in this repository's guidance files or package scripts. Ask a human how changes are verified before claiming a change is tested."\n` +
        `    tool docs\n}\n\n` +
        `ask Verifier("How should the current change set be verified?")\n` +
        `print("No test command discovered at onboarding — see ../onboard-report.md")\n`,
    });
  }

  files.push({
    path: "workflows/change-review.solve",
    signals: [
      "Always generated: review is a routine task in every repository.",
      signals.hotPaths.length > 0
        ? `Hot paths from git history named in the instruction: ${signals.hotPaths.map((hot) => hot.path).join(", ")}.`
        : "No hot-path signals (history unavailable or no repeated paths) — the instruction stays generic.",
    ],
    content:
      HEADER +
      `\nagent Reviewer {\n` +
      `    instruction "Review the change set against the Solve Context pack: check the blast radius, the affected validations, and any protected paths before approving.${
        signals.hotPaths.length > 0
          ? ` Pay extra attention to the most frequently changed areas: ${solveString(signals.hotPaths.map((hot) => hot.path).join(", "))}.`
          : ""
      }"\n` +
      `    tool docs\n}\n\n` +
      `ask Reviewer("Review the current change set.")\n` +
      `print("Review input: ../context-pack.json")\n`,
  });

  if (test || build) {
    const named = [test, build].filter(Boolean) as NonNullable<typeof test>[];
    files.push({
      path: "workflows/ci-triage.solve",
      signals: named.map((fact) => `${fact.kind} command "${fact.command}" from ${fact.source}.`),
      content:
        HEADER +
        `\nagent Triage {\n` +
        `    instruction "When CI fails, reproduce locally with the repository's own commands (${solveString(
          named.map((fact) => fact.command).join("; "),
        )}), read the failure output exactly, and classify it as a real defect, a flake, or an environment problem before changing anything."\n` +
        `    tool docs\n}\n\n` +
        `ask Triage("Triage the latest CI failure.")\n` +
        `print("Local reproduction commands are named in the Triage instruction above.")\n`,
    });
  }

  return files;
}

export function renderReport(
  signals: RepoSignals,
  files: GeneratedFile[],
  pack: PackSummary,
  outDirName: string,
): string {
  const lines: string[] = [];
  lines.push("# SolveLang onboarding — inference report");
  lines.push("");
  lines.push(
    "Generated by `solvelang-onboard`. Every fact below names its source; anything not evidenced was omitted, never invented.",
  );
  lines.push("");
  lines.push("## Signals read");
  lines.push("");
  lines.push(`- Repository files scanned: ${signals.fileCount} (test files: ${signals.testFileCount})`);
  lines.push(
    signals.guidanceFiles.length > 0
      ? `- Guidance files: ${signals.guidanceFiles.join(", ")}`
      : "- Guidance files: none found",
  );
  lines.push(
    signals.commitCount !== null
      ? `- Git history: ${signals.commitCount} commit(s); subjects and changed paths read from the most recent 50`
      : "- Git history: unavailable",
  );
  lines.push("");
  lines.push("### Commands (each with its source)");
  lines.push("");
  if (signals.commands.length === 0) {
    lines.push("- None discovered. No command was invented to fill this gap.");
  } else {
    for (const fact of signals.commands) {
      lines.push(`- ${fact.kind}: \`${fact.command}\` — from ${fact.source}`);
    }
  }
  lines.push("");
  lines.push("### Ecosystems and languages (from layout)");
  lines.push("");
  if (signals.ecosystems.length === 0) lines.push("- No ecosystem marker files found.");
  for (const eco of signals.ecosystems) lines.push(`- ${eco.name} — marker: ${eco.source}`);
  for (const lang of signals.languages.slice(0, 8)) {
    lines.push(`- ${lang.language}: ${lang.files} file(s)`);
  }
  lines.push("");
  lines.push("### Most-changed paths (from git history)");
  lines.push("");
  if (signals.hotPaths.length === 0) {
    lines.push("- None (no path changed more than once in the read window, or history unavailable).");
  } else {
    for (const hot of signals.hotPaths) lines.push(`- ${hot.path} — changed in ${hot.changes} recent commit(s)`);
  }
  lines.push("");
  lines.push("## What was generated");
  lines.push("");
  for (const file of files) {
    lines.push(`### ${outDirName}/${file.path}`);
    for (const signal of file.signals) lines.push(`- ${signal}`);
    lines.push("");
  }
  lines.push(`### ${outDirName}/context-pack.json`);
  lines.push(
    `- Built by the existing Solve Context pack machinery (buildWorkspaceContextPack) over this repository — pack id ${pack.packId}, ${pack.entries} source(s), ${pack.selectedBytes} of ${pack.budgetBytes} budget bytes${pack.truncated ? ", truncated to budget" : ""}.`,
  );
  lines.push("");
  lines.push("## What was NOT inferred");
  lines.push("");
  lines.push("- No deployment, hosting, or release workflow: no signal for one was found, and this tool does not generate one.");
  if (!signals.commands.some((fact) => fact.kind === "test")) {
    lines.push("- No test command: none was stated in a guidance file or manifest, so the validate workflow asks a human instead of guessing.");
  }
  for (const note of signals.notes) lines.push(`- ${note}`);
  lines.push("");
  return lines.join("\n");
}
