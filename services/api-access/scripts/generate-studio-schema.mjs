// Run from any directory after `npm ci` in site. The browser schema is canonical.
import ts from '../../../site/node_modules/typescript/lib/typescript.js';
import { readFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
const sourceRoot = new URL('../../../site/app/studio/core/', import.meta.url);
const outputRoot = new URL('../src/studio-schema/', import.meta.url);
mkdirSync(outputRoot, { recursive: true });
for (const name of ['types', 'schema', 'workspace-schema']) {
  const source = readFileSync(new URL(`${name}.ts`, sourceRoot), 'utf8');
  const digest = createHash('sha256').update(source).digest('hex');
  const output = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022 } }).outputText
    .replaceAll('from "./types"', 'from "./types.js"').replaceAll('from "./schema"', 'from "./schema.js"');
  writeFileSync(new URL(`${name}.js`, outputRoot), `// Generated by scripts/generate-studio-schema.mjs; do not edit.\n// Source SHA-256: ${digest}\n${output}`);
}
